"""Шкала отношений: от ненависти до любви.

Число уровня = позиция в списке. Меньше номер — лучше.
Словами дублируются значения намеренно: в промпт уходит «Нейтральность»,
а не «6» — модель понимает слово, а не индекс.
"""

LEVELS = [
    (0, "Любовь"),
    (1, "Влюблённость"),
    (2, "Влечение"),
    (3, "Дружба"),
    (4, "Привязанность"),
    (5, "Приветливость"),
    (6, "Нейтральность"),  # СТАРТОВЫЙ уровень
    (7, "Неприязнь"),
    (8, "Вражда"),
    (9, "Ненависть"),
]

NEUTRAL_LEVEL = 6
LEVEL_PROGRESS_CAP = 100  # очков до перехода на соседний уровень
LEVEL_NAMES = {number: name for number, name in LEVELS}


def level_name(level: int) -> str:
    return LEVEL_NAMES[clamp_level(level)]


def clamp_level(level: int) -> int:
    """0..9 — не выходит за границы шкалы."""
    return max(0, min(9, level))
