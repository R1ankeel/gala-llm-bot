"""RelationshipProvider — read-path: тональная инструкция по уровню
отношений. Реализация StateProvider Protocol (core/layers.py)."""


class RelationshipProvider:
    """Возвращает словесную инструкцию по тону, НЕ число и не прогресс.

    Нейтральный уровень (6) — дефолт, инструкция не добавляется вообще
    (экономим токены: писать «ты нейтральна» бессмысленно — модель и так
    так себя ведёт по умолчанию).
    """

    def __init__(self, store):
        self.store = store

    def render(self, addressee_nick: str) -> str | None:
        state = self.store.get(addressee_nick)
        return _instruction_for_level(state.level)


def _instruction_for_level(level: int) -> str | None:
    if level <= 2:  # Любовь / Влюблённость / Влечение
        return (
            "Ты очень тепло относишься к этому собеседнику, тебе приятно "
            "с ним общаться, можешь проявлять симпатию."
        )
    if level <= 4:  # Дружба / Привязанность
        return (
            "Ты дружелюбно относишься к этому собеседнику, он тебе симпатичен."
        )
    if level == 5:  # Приветливость
        return "Ты относишься к собеседнику скорее позитивно."
    if level == 6:  # Нейтральность — дефолт, ничего не добавляем
        return None
    if level == 7:  # Неприязнь
        return (
            "Этот собеседник тебе не особо приятен, ты можешь быть прохладен "
            "или слегка колок с ним."
        )
    # 8-9: Вражда / Ненависть
    return (
        "Ты неприязненно/враждебно настроен к этому собеседнику, можешь "
        "быть резким и язвительным."
    )
